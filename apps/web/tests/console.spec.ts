import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
import {resolve} from 'node:path';
const env=readFileSync(resolve('../../.env'),'utf8');
const password=env.split('\n').find(x=>x.startsWith('OPERATOR_PASSWORD='))!.split('=').slice(1).join('=').trim();
test('operator can validate CSV, queue and cancel a task, and inspect operation readiness',async({page})=>{
  await page.goto('/');
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Sign in'}).click();
  await expect(page.getByRole('heading',{name:'Every action. Accounted for.'})).toBeVisible();
  await page.screenshot({path:'../../docs/screenshots/overview.png',fullPage:true});
  await page.getByRole('navigation').getByRole('link',{name:'New task'}).click();
  await page.getByLabel('Order CSV').setInputFiles({name:'orders.csv',mimeType:'text/csv',buffer:Buffer.from('order_id,expected_delivery\nORD-102,2026-11-10\n')});
  await expect(page.getByRole('cell',{name:'ORD-102',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Start verified execution'}).click();
  await expect(page.getByText('QUEUED',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Request cancellation'}).click();
  await expect(page.getByText('CANCELED',{exact:true})).toBeVisible();
  await page.getByRole('navigation').getByRole('link',{name:'Operation library'}).click();
  await expect(page.getByRole('heading',{name:'get_order_status',exact:true})).toBeVisible();
  await page.screenshot({path:'../../docs/screenshots/operations.png',fullPage:true});
  await page.getByRole('navigation').getByRole('link',{name:'Reliability lab'}).click();
  await expect(page.getByRole('button',{name:'Switch to version 2'})).toBeEnabled();
  await page.getByRole('button',{name:'Switch to version 2'}).click();
  await expect(page.getByRole('status')).toHaveText('Portal layout changed');
  await page.getByRole('button',{name:'Switch to version 1'}).click();
  await page.getByRole('button',{name:'Sign out'}).click();
  await expect(page.getByRole('heading',{name:'Operator sign in'})).toBeVisible();
});
