import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
import {resolve} from 'node:path';
test.skip(process.env.SKG_FULL_STACK!=='1','Requires the complete Docker stack');
test('revalidate, compare versions, reject stale CSV, recover expired session and sign out on mobile',async({page,context})=>{
  test.setTimeout(120000);
  const env=readFileSync(resolve('../../.env'),'utf8');
  const password=env.split('\n').find(x=>x.startsWith('OPERATOR_PASSWORD='))!.split('=').slice(1).join('=').trim();
  const login=async()=>{
    await page.getByLabel('Username',{exact:true}).fill('operator');
  await page.getByLabel('Password',{exact:true}).fill(password);
    await page.getByRole('button',{name:'Sign in',exact:true}).click();
    await expect(page.getByRole('navigation')).toBeVisible();
  };
  await page.goto('/');
  await login();
  await page.getByRole('navigation').getByRole('link',{name:'Operation library'}).click();
  const operation=page.locator('.panel').filter({has:page.getByRole('heading',{name:'get_order_status',exact:true})});
  await operation.getByRole('button',{name:'Validate',exact:true}).click();
  await expect(page.locator('.title .badge')).toHaveText('VERIFIED',{timeout:90000});
  await page.getByRole('navigation').getByRole('link',{name:'Operation library'}).click();
  await operation.getByText('Compare immutable versions',{exact:true}).click();
  await expect(operation.getByLabel('From version')).toBeVisible();
  await expect(operation.getByText('contract.revalidated_from',{exact:true})).toBeVisible();
  await page.screenshot({path:'../../docs/screenshots/version-comparison.png',fullPage:true});
  await page.getByRole('navigation').getByRole('link',{name:'New task'}).click();
  await page.getByRole('button',{name:'Try sample orders'}).click();
  await expect(page.getByRole('cell',{name:'ORD-101',exact:true})).toBeVisible();
  await expect(page.getByRole('cell',{name:'ORD-103',exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'Start verified execution'})).toBeEnabled();
  const upload=page.getByLabel('Order CSV');
  await upload.setInputFiles({name:'valid.csv',mimeType:'text/csv',buffer:Buffer.from('order_id,expected_delivery\nORD-102,2026-11-10\n')});
  await expect(page.getByRole('button',{name:'Start verified execution'})).toBeEnabled();
  await upload.setInputFiles({name:'invalid.csv',mimeType:'text/csv',buffer:Buffer.from('wrong,headers\n1,2\n')});
  await expect(page.getByRole('alert')).toBeVisible();
  await expect(page.getByRole('button',{name:'Start verified execution'})).toBeDisabled();
  await context.clearCookies();
  await page.getByRole('navigation').getByRole('link',{name:'Verified results'}).click();
  await expect(page.getByRole('heading',{name:'Sign in'})).toBeVisible();
  await login();
  await page.setViewportSize({width:390,height:844});
  await expect(page.getByRole('button',{name:'Sign out'})).toBeVisible();
  await page.getByRole('button',{name:'Sign out'}).click();
  await expect(page.getByRole('heading',{name:'Sign in'})).toBeVisible();
});
