import {test,expect} from '@playwright/test';
import {randomUUID} from 'node:crypto';
test.skip(process.env.SKG_FULL_STACK!=='1','Requires Docker with a validated read operation');

test('users sign up, execute private read tasks, log in again, and cannot access another account',async({page})=>{
  test.setTimeout(120000);
  const username='user-'+randomUUID().slice(0,8);
  const password='Test-'+randomUUID();
  await page.goto('/');
  await page.getByRole('button',{name:'Create a new account',exact:true}).click();
  await page.getByLabel('Username',{exact:true}).fill(username);
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByLabel('Confirm password',{exact:true}).fill(password+'wrong');
  await page.getByRole('button',{name:'Create account',exact:true}).click();
  await expect(page.getByRole('alert')).toHaveText('Passwords do not match.');
  await page.getByLabel('Confirm password',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Create account',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Every action. Accounted for.'})).toBeVisible();
  await expect(page.getByText(username+' · user',{exact:true})).toBeVisible();
  await expect(page.getByRole('navigation').getByRole('link',{name:'Approval center'})).toHaveCount(0);
  await expect(page.getByRole('navigation').getByRole('link',{name:'Reliability lab'})).toHaveCount(0);
  await page.getByRole('navigation').getByRole('link',{name:'Operation library'}).click();
  await expect(page.getByRole('heading',{name:'get_order_status',exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'Learn read workflow'})).toHaveCount(0);
  await page.getByRole('navigation').getByRole('link',{name:'New task'}).click();
  await page.getByLabel('Order CSV').setInputFiles({name:'orders.csv',mimeType:'text/csv',buffer:Buffer.from('order_id,expected_delivery\nORD-102,2026-11-10\n')});
  await expect(page.getByRole('cell',{name:'ORD-102',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Start verified execution'}).click();
  await expect(page.locator('.title .badge')).toHaveText('VERIFIED',{timeout:90000});
  const jobId=page.url().split('/').pop()!;
  await expect(page.getByRole('link',{name:'Prepare request'})).toHaveCount(0);
  await page.screenshot({path:'../../docs/screenshots/user-workspace.png',fullPage:true});
  await page.getByRole('button',{name:'Sign out'}).click();
  await page.getByLabel('Username',{exact:true}).fill(username);
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(page.locator('.title .badge')).toHaveText('VERIFIED');
  await page.getByRole('button',{name:'Sign out'}).click();
  await page.getByRole('button',{name:'Create a new account',exact:true}).click();
  await page.getByLabel('Username',{exact:true}).fill('user-'+randomUUID().slice(0,8));
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByLabel('Confirm password',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Create account',exact:true}).click();
  await expect(page.getByRole('navigation')).toBeVisible();
  // The URL is intentionally retained; account ownership is enforced by the server.
  expect((await page.request.get('/api/v1/tasks/'+jobId)).status()).toBe(404);
  await page.getByRole('navigation').getByRole('link',{name:'Overview',exact:true}).click();
  await expect(page.getByRole('heading',{name:'No executions yet'})).toBeVisible();
  await page.getByRole('button',{name:'Sign out'}).click();
});
